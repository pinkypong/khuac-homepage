// (0,0) is the Null Island sentinel some cameras/apps write when GPS failed
// to get a fix rather than omitting the tag - treat it the same as missing.
export function isValidGps(lat: number | null | undefined, lng: number | null | undefined): boolean {
  if (lat == null || lng == null) return false;
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return false;
  if (lat === 0 && lng === 0) return false;
  if (lat < -90 || lat > 90) return false;
  if (lng < -180 || lng > 180) return false;
  return true;
}
